using ComfyTyped.Core;
using ComfyTyped.Generated;
using ComfyTyped.SwarmUI;
using ComfyTyped.Types;
using Newtonsoft.Json.Linq;
using SwarmUI.Builtin_ComfyUIBackend;
using VideoStages.Architectures.Abstractions;
using VideoStages.Generated;

namespace VideoStages.Architectures.Ltx2;

internal sealed class LtxAudioInjector(
    WorkflowGenerator g,
    IArchitectureRootMediaResizer rootVideoStageResizer)
{
    private const int AudioInjectionIdBase = 52300;
    private const int AudioInjectionEnsureFallbackSlot = 50;

    /// <summary>
    /// Injects <paramref name="audio"/> as the sampling audio latent. With no
    /// <paramref name="preserveWindows"/>, the whole track is preserved (solid 0.0 mask). With
    /// windows, only those seconds-ranges are preserved and the gaps are regenerated by the model
    /// — the audio-segment conditioning path (segments over no locked base track).
    /// </summary>
    public bool TryInject(
        WGNodeData audio,
        bool matchVideoLengthToAudio = true,
        IReadOnlyList<(double Start, double End)> preserveWindows = null)
    {
        if (audio is null || !g.IsLTXV2() || g.CurrentAudioVae is null)
        {
            return false;
        }

        WorkflowBridge bridge = WorkflowBridge.Create(g.Workflow);
        (List<string> concatIds, HashSet<string> removableSourceIds) = FindConcatsToReplace(bridge);
        if (concatIds.Count == 0)
        {
            return false;
        }

        WGNodeData adjustedAudio = audio;
        if (matchVideoLengthToAudio)
        {
            JToken lengthFramesAudioSource = LtxAudioPathResolution.ResolveLengthToFramesAudioSource(
                bridge,
                audio.Path,
                g.GetStableDynamicID(AudioInjectionIdBase + AudioInjectionEnsureFallbackSlot, 0));
            SwarmAudioLengthToFramesNode lengthToFrames = CreateLengthToFramesNode(
                bridge,
                lengthFramesAudioSource,
                ResolveFramesPerSecond());
            ApplyFramesConnectionToRemovableAudioSources(bridge, removableSourceIds, lengthToFrames.Frames);
            BridgeSync.SyncLastId(g);
            LtxFrameCountConnector.ApplyToExistingSources(g, WorkflowBridge.ToPath(lengthToFrames.Frames));
            adjustedAudio = new(
                WorkflowBridge.ToPath(lengthToFrames.Audio),
                g,
                WGNodeData.DT_AUDIO,
                g.CurrentAudioVae.Compat);
        }

        WGNodeData encodedAudio = adjustedAudio.EncodeToLatent(g.CurrentAudioVae);
        bridge = WorkflowBridge.Create(g.Workflow);
        NodeOutput<LatentType> maskedLatent = preserveWindows is { Count: > 0 }
            ? CreateWindowedAudioMaskNode(bridge, encodedAudio.Path, preserveWindows, stableIdSlot: 0).Latent
            : CreateAudioMaskNode(bridge, encodedAudio.Path).LATENT;
        ReplaceAudioLatentConnections(bridge, concatIds, maskedLatent);
        RemoveUnusedSourceNodes(bridge, removableSourceIds);
        return true;
    }

    /// <summary>
    /// Encodes <paramref name="audio"/> and applies the preserve-windows noise mask WITHOUT touching any
    /// concat — for clips whose AV latent is built later from <c>AttachedAudio</c>: core
    /// <c>AsSamplingLatent</c> concats a pre-encoded audio latent as-is, keeping this mask, whereas raw
    /// attached audio would be baked fully-preserved (locking silent-bed gaps). Returns null when the
    /// graph state can't support it (not LTXV2 / no audio VAE / no windows).
    /// </summary>
    public WGNodeData TryBuildPreserveWindowedAudioLatent(
        WGNodeData audio,
        IReadOnlyList<(double Start, double End)> preserveWindows,
        int stableIdSlot)
    {
        if (audio is null
            || preserveWindows is not { Count: > 0 }
            || !g.IsLTXV2()
            || g.CurrentAudioVae is null)
        {
            return null;
        }
        WGNodeData encodedAudio = audio.EncodeToLatent(g.CurrentAudioVae);
        WorkflowBridge bridge = WorkflowBridge.Create(g.Workflow);
        SwarmSetAudioMaskWindowsNode mask = CreateWindowedAudioMaskNode(
            bridge, encodedAudio.Path, preserveWindows, stableIdSlot);
        return new WGNodeData(
            WorkflowBridge.ToPath(mask.Latent),
            g,
            WGNodeData.DT_LATENT_AUDIO,
            g.CurrentAudioVae.Compat);
    }

    private static (List<string> ConcatIds, HashSet<string> RemovableSourceIds)
        FindConcatsToReplace(WorkflowBridge bridge)
    {
        List<string> concatIds = [];
        HashSet<string> removableSourceIds = [];
        foreach (LTXVConcatAVLatentNode concat in bridge.Graph.NodesOfType<LTXVConcatAVLatentNode>())
        {
            if (concat.AudioLatent.Connection?.Node is not LTXVEmptyLatentAudioNode emptyAudio)
            {
                continue;
            }
            concatIds.Add(concat.Id);
            removableSourceIds.Add(emptyAudio.Id);
        }
        return (concatIds, removableSourceIds);
    }

    private SwarmAudioLengthToFramesNode CreateLengthToFramesNode(WorkflowBridge bridge, JToken audioPath, int fps)
    {
        SwarmAudioLengthToFramesNode node = new SwarmAudioLengthToFramesNode().With(
            FrameRate: fps);
        node.AudioInput.TryConnectFromPath(bridge, audioPath as JArray);
        bridge.AddNode(node, g.GetStableDynamicID(AudioInjectionIdBase + 100, 0));
        return node;
    }

    private int ResolveFramesPerSecond()
    {
        int fps = g.GetVideoExecutionPlanContext()?.Plan.FramesPerSecond
            ?? g.UserInput.Get(
                SwarmUI.Text2Image.T2IParamTypes.VideoFPS,
                LtxStageRuntimeSettings.DefaultFps);
        return fps > 0 ? fps : LtxStageRuntimeSettings.DefaultFps;
    }

    private static void ApplyFramesConnectionToRemovableAudioSources(
        WorkflowBridge bridge,
        HashSet<string> sourceIds,
        NodeOutput<IntType> framesOutput)
    {
        foreach (string sourceId in sourceIds)
        {
            LTXVEmptyLatentAudioNode emptyAudio = bridge.Graph.GetNode<LTXVEmptyLatentAudioNode>(sourceId);
            if (emptyAudio is null)
            {
                continue;
            }
            emptyAudio.FramesNumber.ConnectTo(framesOutput);
            bridge.SyncNode(emptyAudio);
        }
    }

    private SetLatentNoiseMaskNode CreateAudioMaskNode(WorkflowBridge bridge, JArray encodedAudioPath)
    {
        int width = g.UserInput.GetImageWidth();
        int height = g.UserInput.GetImageHeight();
        if (rootVideoStageResizer.TryGetRootStageResolution(out int rootWidth, out int rootHeight))
        {
            width = rootWidth;
            height = rootHeight;
        }

        SolidMaskNode solidMask = new SolidMaskNode().With(
            Value: 0.0,
            Width: width,
            Height: height);
        bridge.AddNode(solidMask, g.GetStableDynamicID(AudioInjectionIdBase + 200, 0));

        SetLatentNoiseMaskNode setMask = new SetLatentNoiseMaskNode().With(
            Mask: solidMask.MASK);
        setMask.Samples.TryConnectFromPath(bridge, encodedAudioPath);
        bridge.AddNode(setMask, g.GetStableDynamicID(AudioInjectionIdBase + 300, 0));
        return setMask;
    }

    /// <summary>Windowed variant of <see cref="CreateAudioMaskNode"/>: preserve only the given
    /// seconds-windows of the encoded audio; the model regenerates the gaps.</summary>
    private SwarmSetAudioMaskWindowsNode CreateWindowedAudioMaskNode(
        WorkflowBridge bridge,
        JArray encodedAudioPath,
        IReadOnlyList<(double Start, double End)> preserveWindows,
        int stableIdSlot)
    {
        JArray windowsJson = new(preserveWindows.Select(window => new JObject
        {
            ["start"] = window.Start,
            ["end"] = window.End,
        }));
        SwarmSetAudioMaskWindowsNode node = new SwarmSetAudioMaskWindowsNode().With(
            Windows: windowsJson.ToString(Newtonsoft.Json.Formatting.None),
            GapMaskValue: 1.0);
        node.Samples.TryConnectFromPath(bridge, encodedAudioPath);
        node.AudioVae.ConnectFromPath(bridge, g.CurrentAudioVae.Path);
        bridge.AddNode(node, g.GetStableDynamicID(AudioInjectionIdBase + 400, stableIdSlot));
        return node;
    }

    private static void ReplaceAudioLatentConnections(
        WorkflowBridge bridge,
        List<string> concatIds,
        NodeOutput<LatentType> maskedLatent)
    {
        foreach (string concatId in concatIds)
        {
            LTXVConcatAVLatentNode concat = bridge.Graph.GetNode<LTXVConcatAVLatentNode>(concatId);
            if (concat is null)
            {
                continue;
            }
            concat.AudioLatent.ConnectTo(maskedLatent);
            bridge.SyncNode(concat);
        }
    }

    private void RemoveUnusedSourceNodes(WorkflowBridge bridge, HashSet<string> removableSourceIds)
    {
        g.UsedInputs = null;
        foreach (string sourceId in removableSourceIds)
        {
            if (!g.NodeIsConnectedAnywhere(sourceId))
            {
                bridge.RemoveNode(sourceId);
            }
        }
    }

}
